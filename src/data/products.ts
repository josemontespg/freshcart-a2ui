const PRODUCT_BY_ID_MAP = new Map<string, Product>(
  PRODUCTS.map((product) => [product.id, product])
);

/**
 * Alias map ensuring any alternative shorthand IDs referenced by scenario
 * prompts resolve cleanly to canonical `Product` records.
 */
const PRODUCT_ID_ALIASES: Record<string, string> = {
  'prod-atlantic-salmon-value': 'prod-atlantic-salmon',
  'prod-org-eggs': 'prod-pasture-eggs',
  'prod-protein-oats': 'prod-tj-protein-oats',
  'prod-almond-butter': 'prod-sprouts-almond-butter',
  'prod-peanut-butter': 'prod-sprouts-peanut-butter',
  'prod-oat-milk': 'prod-sprouts-oat-milk',
  'prod-grass-fed-beef': 'prod-sprouts-grass-bison',
};

export function getProductById(productId: string): Product | undefined {
  const direct = PRODUCT_BY_ID_MAP.get(productId);
  if (direct) {
    return direct;
  }
  const canonicalId = PRODUCT_ID_ALIASES[productId];
  return canonicalId ? PRODUCT_BY_ID_MAP.get(canonicalId) : undefined;
}

export function getProductsByStore(storeId: StoreId): Product[] {
  return PRODUCTS.filter((product) => product.storeId === storeId);
}

export function getProductOptimizationLinks(
  productId: string
): ProductOptimizationLinks {
  const product = getProductById(productId);
  if (!product) {
    return {};
  }
  return {
    backup: product.suggestedBackupProductId
      ? getProductById(product.suggestedBackupProductId)
      : undefined,
    organicUpgrade: product.organicUpgradeProductId
      ? getProductById(product.organicUpgradeProductId)
      : undefined,
    budgetAlternative: product.budgetAlternativeProductId
      ? getProductById(product.budgetAlternativeProductId)
      : undefined,
  };
}

export function getSubstitutesForProduct(productId: string): Product[] {
  const product = getProductById(productId);
  if (!product) {
    return [];
  }

  const seenIds = new Set<string>([product.id]);
  const substitutes: Product[] = [];

  const pushIfValid = (candidate: Product | undefined) => {
    if (
      candidate &&
      !seenIds.has(candidate.id) &&
      candidate.stockStatus !== 'out_of_stock'
    ) {
      seenIds.add(candidate.id);
      substitutes.push(candidate);
    }
  };

  const links = getProductOptimizationLinks(product.id);
  pushIfValid(links.backup);
  pushIfValid(links.organicUpgrade);
  pushIfValid(links.budgetAlternative);

  // Add same-category products in the same store first
  for (const candidate of PRODUCTS) {
    if (
      candidate.storeId === product.storeId &&
      candidate.category === product.category
    ) {
      pushIfValid(candidate);
    }
  }

  // Fallback to same-category products across all stores
  for (const candidate of PRODUCTS) {
    if (candidate.category === product.category) {
      pushIfValid(candidate);
    }
  }

  return substitutes.slice(0, 6);
}
